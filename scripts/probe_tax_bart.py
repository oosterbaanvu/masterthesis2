#!/usr/bin/env python
"""Out-of-generator validity probe on Raha Tax (BART-generated errors).

Question: does CDC's ranking quality on errors generated by *our* injector (frequency-weighted
category swaps, plausible substitutions) agree with its ranking quality on errors generated by an
*independent* generator (BART, as published in the Raha Tax pair) in the same columns?

Design (qualification only, nothing tuned on the outcome):
* Typing: numeric columns parsed as numbers; zip and area_code as numeric features (zip codes are
  geographically ordered, so tree splits can learn zip -> state); high-cardinality strings
  (names, city, phone) are excluded. Cells whose dirty value does not parse become NaN.
* Published differences that are formatting artefacts (leading zeros, '0' vs '0.0', doubled
  apostrophes) are excluded from the BART error set (see dataset_qualification.md).
* Split: 30,000 sampled rows; CDC is fitted on the CLEAN values of 20,000 rows and scored on the
  DIRTY values of 10,000 held-out rows (BART errors) and, separately, on the clean values of the
  same held-out rows with our injected errors (1% per target column, ECAR).
"""

from __future__ import annotations

import json
import sys
import warnings

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from dq_framework import paths
from dq_framework.contracts import Column, Contract
from dq_framework.datasets import get_spec, load_pair
from dq_framework.detectors.cdc import ConformalDataCleaningHGB
from dq_framework.injection import Scenario, inject

warnings.filterwarnings("ignore")
CAT = ["gender", "state", "marital_status", "has_child"]
NUM = ["salary", "rate", "single_exemp", "married_exemp", "child_exemp", "zip", "area_code"]
TARGETS = ["state", "marital_status", "has_child", "single_exemp", "child_exemp"]


def typed(df: pd.DataFrame) -> pd.DataFrame:
    out = pd.DataFrame(index=df.index)
    for c in CAT:
        out[c] = df[c].astype("string")
    for c in NUM:
        out[c] = pd.to_numeric(df[c], errors="coerce").astype("float64")
    return out


def main() -> int:
    dirty, clean = load_pair(get_spec("raha_tax"))
    rng = np.random.default_rng(7)
    idx = rng.choice(len(clean), 30_000, replace=False)
    ref_idx, test_idx = idx[:20_000], idx[20_000:]
    td, tc = typed(dirty), typed(clean)
    # BART error set per column: typed values differ and the raw difference is not a formatting artefact
    bart = {}
    for c in TARGETS:
        raw_diff = dirty[c] != clean[c]
        a, b = td[c], tc[c]
        if c in CAT:
            val = raw_diff & (a.astype(str) != b.astype(str))
        else:
            val = raw_diff & ~(a.notna() & b.notna() & (a == b))
        bart[c] = val
    cols = [Column(c, "categorical") for c in CAT] + [Column(c, "numeric") for c in NUM]
    contract = Contract("tax_typed", "tax", "probe", None, cols, {}, [])
    ref = tc.iloc[ref_idx].reset_index(drop=True).assign(_row_id=np.arange(len(ref_idx)))
    test_dirty = td.iloc[test_idx].reset_index(drop=True).assign(_row_id=np.arange(10**6, 10**6 + len(test_idx)))
    test_clean = tc.iloc[test_idx].reset_index(drop=True).assign(_row_id=test_dirty["_row_id"])
    det = ConformalDataCleaningHGB(confidence=0.999, max_iter=100, target_columns=TARGETS).fit(ref, contract)
    s_bart = det.score(test_dirty.assign(_scenario_id="bart")).scores
    out: dict = {"n_reference": len(ref), "n_test": len(test_idx), "per_column": {}}
    for c in TARGETS:
        y = bart[c].iloc[test_idx].to_numpy()
        sc = s_bart[s_bart["column"] == c].reset_index(drop=True)
        present = sc["score"].notna().to_numpy()
        r = {"bart_errors_in_test": int(y.sum()), "bart_errors_unparseable": int((y & ~present).sum())}
        yy = y[present]
        if yy.any() and (~yy).any():
            r["auc_bart"] = float(roc_auc_score(yy, sc.loc[present, "score"]))
            r["recall_flag_bart"] = float(sc.loc[present, "flag"][yy].mean())
        # our injector on the same column (clean held-out rows), ECAR at 1%
        op = ("category_swap", {"weighing": "frequency"}) if c in CAT else ("plausible_substitution", {})
        aucs = []
        for seed in (11, 22, 33):
            inj = inject(test_clean, Scenario("tax_typed", c, op[0], "soft_ecar", 0.01, seed, op[1], {}), contract, ref)
            so = det.score(inj.corrupted.assign(_scenario_id="x")).scores
            so = so[so["column"] == c]
            yi = so["_row_id"].isin(set(inj.log["_row_id"]))
            aucs.append(float(roc_auc_score(yi, so["score"])))
        r["auc_ours_mean"] = float(np.mean(aucs))
        r["auc_ours_range"] = [float(min(aucs)), float(max(aucs))]
        r["our_operation"] = op[0]
        out["per_column"][c] = r
    qdir = paths.RESULTS_DIR / "qualification"
    qdir.mkdir(parents=True, exist_ok=True)
    (qdir / "tax_bart_probe.json").write_text(json.dumps(out, indent=2))
    print(json.dumps(out, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
