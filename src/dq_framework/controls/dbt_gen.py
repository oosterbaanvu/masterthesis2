"""Generate dbt models and data tests from a source contract.

Output (committed, regenerated by ``dqf controls generate``):

* ``dbt/models/generated/stg_<dataset>.sql``  - staging model over the batch Parquet file
* ``dbt/models/generated/<dataset>.yml``      - model-level data tests, one per active rule

Unsupported or disabled rules are emitted as YAML comments so the generated
project documents what was deliberately *not* enforced.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from dq_framework import paths
from dq_framework.contracts import Contract, Rule, quote_ident

GENERATED_DIR = paths.DBT_DIR / "models" / "generated"
HEADER = "-- GENERATED from config/contracts/{ds}.yaml by `dqf controls generate`. Do not edit.\n"


def model_name(contract: Contract) -> str:
    return f"stg_{contract.dataset}"


def _sql_literal(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int | float):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def _values_sql(contract: Contract, rule: Rule) -> str:
    vals = rule.params.get("values")
    if vals is None and rule.params.get("from_documented"):
        vals = contract.column(rule.columns[0]).documented_values
    if not vals:
        raise ValueError(f"{rule.id}: accepted_values without values")
    return ", ".join(_sql_literal(v) for v in vals)


def _test_entry(contract: Contract, rule: Rule) -> list[dict[str, Any]]:
    """One rule -> one or more dbt generic test invocations (multi-column not_null expands per column)."""
    cols_text = ",".join(rule.columns)
    entries: list[tuple[str, str, dict[str, Any]]] = []
    k = rule.kind
    if k == "not_null":
        for col in rule.columns:
            entries.append(
                (f"{rule.id}__{col}", "dq_not_null",
                 {"rule_id": rule.id, "column_sql": quote_ident(col), "column_name_text": col})
            )
    elif k == "unique":
        col = rule.columns[0]
        entries.append((rule.id, "dq_unique", {"rule_id": rule.id, "column_sql": quote_ident(col), "column_name_text": col}))
    elif k == "accepted_values":
        col = rule.columns[0]
        entries.append(
            (rule.id, "dq_accepted_values",
             {"rule_id": rule.id, "column_sql": quote_ident(col), "column_name_text": col,
              "values_sql": _values_sql(contract, rule)})
        )
    elif k == "range":
        col = rule.columns[0]
        args: dict[str, Any] = {"rule_id": rule.id, "column_sql": quote_ident(col), "column_name_text": col}
        if rule.params.get("min") is not None:
            args["min_value"] = rule.params["min"]
        if rule.params.get("max") is not None:
            args["max_value"] = rule.params["max"]
        entries.append((rule.id, "dq_range", args))
    elif k == "expression":
        observed = " || '|' || ".join(f"coalesce(cast({quote_ident(c)} as varchar), 'NULL')" for c in rule.columns)
        entries.append(
            (rule.id, "dq_expression",
             {"rule_id": rule.id, "condition": rule.params["expression"], "columns_text": cols_text,
              "observed_sql": observed})
        )
    elif k == "envelope":
        entries.append(
            (rule.id, "dq_envelope", {"rule_id": rule.id, "expression": rule.params["expression"], "columns_text": cols_text})
        )
    elif k == "rare_category":
        entries.append(
            (rule.id, "dq_rare_category",
             {"rule_id": rule.id, "expression": rule.params["expression"], "columns_text": cols_text})
        )
    else:
        raise ValueError(k)
    out = []
    for name, macro, args in entries:
        out.append({macro: {"name": _safe_name(f"{contract.dataset}__{name}"), "arguments": args,
                            "config": {"meta": {"rule_id": rule.id, "tier": rule.tier, "status": rule.status}}}})
    return out


def _safe_name(s: str) -> str:
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in s).lower()


def render(contract: Contract) -> tuple[str, str]:
    """Return (model_sql, schema_yml) for a contract."""
    cols = [quote_ident(c) for c in contract.column_names]
    key = [quote_ident(contract.row_id)] if contract.row_id else []
    select_list = ",\n    ".join(["_scenario_id", "_row_id", *key, *cols])
    sql = (
        HEADER.format(ds=contract.dataset)
        + "-- Batch under test (one or more scenarios), typed by the Python loader from the contract.\n"
        + "select\n    " + select_list + "\nfrom read_parquet('{{ var(\"batch_path\") }}')\n"
    )
    tests: list[dict[str, Any]] = []
    skipped: list[str] = []
    for r in contract.rules:
        if r.active:
            tests.extend(_test_entry(contract, r))
        else:
            skipped.append(f"#   {r.id} ({r.kind}, status={r.status}, enabled={r.enabled}): {r.evidence.strip()}")
    doc = {
        "version": 2,
        "models": [
            {
                "name": model_name(contract),
                "description": contract.description.strip(),
                "config": {"meta": {"dataset": contract.dataset, "contract": f"config/contracts/{contract.dataset}.yaml"}},
                "data_tests": tests,
            }
        ],
    }
    yml = HEADER.replace("--", "#").format(ds=contract.dataset)
    if skipped:
        yml += "# Rules recorded in the contract but NOT enforced:\n" + "\n".join(skipped) + "\n"
    yml += yaml.safe_dump(doc, sort_keys=False, width=120, allow_unicode=True)
    return sql, yml


def write(contract: Contract, out_dir: Path = GENERATED_DIR) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    sql, yml = render(contract)
    p_sql = out_dir / f"{model_name(contract)}.sql"
    p_yml = out_dir / f"{contract.dataset}.yml"
    p_sql.write_text(sql, encoding="utf-8")
    p_yml.write_text(yml, encoding="utf-8")
    return [p_sql, p_yml]
